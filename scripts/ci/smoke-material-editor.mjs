import assert from 'node:assert/strict';

export async function runMaterialEditorSmoke(browser, baseUrl) {
    const page = await browser.newPage();
    const errors = []; page.on('pageerror', (e) => errors.push(e.message));
    try {
        await page.goto(`${baseUrl}/__smoke_blank`, { waitUntil: 'domcontentloaded' });
        const result = await page.evaluate(async () => {
            const T = await import('three');
            const { createMaterialEditor } = await import('/scripts/modules/ui/material-editor.js');
            const { captureParsedMaterials } = await import('/scripts/modules/material/scene-materials.js');
            const { validateFlowNetwork, createFlowField, createFlowNetworkEditor } = await import('/scripts/modules/material/flow-network.js');
            const { createBackgroundController } = await import('/scripts/modules/render/background-controller.js');
            const { createRoomMaterialSettings } = await import('/scripts/modules/collab/material-settings.js');
            document.body.innerHTML = '<button id="sceneTab">Сцена</button><button id="materialsTab">Материалы</button><div id="scenePanel"></div><section id="materialEditor" hidden></section>';
            const renderer = new T.WebGLRenderer(); renderer.setSize(256, 256); document.body.append(renderer.domElement);
            let thumbnailRenders = 0;
            const render = renderer.render.bind(renderer);
            renderer.render = (...args) => { thumbnailRenders++; return render(...args); };
            const scene = new T.Scene(), world = new T.Group(), root = new T.Group(); scene.add(world); world.add(root);
            world.position.set(-100000, 0, -200000); root.position.set(100000, 3, 200000);
            const original = new T.MeshPhysicalMaterial({ color: '#a65322', roughness: .82 }); original.name = 'Кирпич';
            const mapCanvas = document.createElement('canvas'); mapCanvas.width = mapCanvas.height = 512;
            mapCanvas.getContext('2d').fillRect(0, 0, 512, 512); original.map = new T.CanvasTexture(mapCanvas);
            const a = new T.Mesh(new T.PlaneGeometry(10, 10), original); a.rotation.x = -Math.PI / 2;
            const b = new T.Mesh(a.geometry, original); b.rotation.x = -Math.PI / 2; b.position.x = 12; root.add(a, b);
            captureParsedMaterials(root);
            const camera = new T.PerspectiveCamera(50, 1, .1, 100); camera.position.set(0, 15, 0); camera.up.set(0, 0, -1); camera.lookAt(0, 3, 0); camera.updateMatrixWorld();
            scene.add(new T.HemisphereLight(0xffffff, 0x555555, 3));
            const controls = { enabled: true, target: new T.Vector3(0, 3, 0) };
            const models = [{ obj: root, name: 'fixture.glb', scope: { roomId: 'r', modelId: 'm' } }];
            const editor = createMaterialEditor({ renderer, rendererReady: Promise.resolve(), scene, world, camera, controls, loadedModels: models, requestRender() {}, getEnvironment() { return null; } });
            document.querySelector('#materialsTab').click();
            const cards = document.querySelectorAll('.me-card').length;
            await readyThumbnails();
            const thumbnail = document.querySelector('.me-card img').src.startsWith('data:image/png');
            const texturePreview = document.querySelector('[data-map-image=map]'); await texturePreview.decode();
            const texturePreviewSmall = texturePreview.naturalWidth === 128 && original.map.image.width === 512;
            const other = new T.Mesh(a.geometry, new T.MeshPhysicalMaterial({ color: '#929ba5', metalness: 1 }));
            other.material.name = 'Металл'; other.position.x = 24; root.add(other); editor.refresh();
            async function readyThumbnails() {
                for (let i = 0; i < 250 && [...document.querySelectorAll('.me-card img')].some((image) => !image.src.startsWith('data:image/png')); i++) await new Promise((resolve) => setTimeout(resolve, 20));
            }
            await readyThumbnails();
            const card = document.querySelector(`[data-material="${original.uuid}"]`);
            const beforeSelection = thumbnailRenders, imageBeforeSelection = card.querySelector('img');
            card.click();
            const selectionKeepsThumbnail = document.querySelector(`[data-material="${original.uuid}"] img`) === imageBeforeSelection;
            document.querySelector('#sceneTab').click(); document.querySelector('#materialsTab').click();
            await new Promise((resolve) => setTimeout(resolve, 100));
            const thumbnailCache = thumbnailRenders === beforeSelection;
            const edit = document.querySelector('#me-roughness'); edit.value = '.21'; edit.dispatchEvent(new Event('change', { bubbles: true }));
            const sharedEdit = a.material === b.material && Math.abs(a.material.roughness - .21) < 1e-6;
            await readyThumbnails();
            const onlyEditedThumbnailRendered = thumbnailRenders === beforeSelection + 1;
            root.remove(other); editor.refresh();
            editor.setMode(true); const parseRestored = a.material.roughness === .82 && a.material === b.material;
            editor.setMode(false); const editsRestored = a.material.roughness === .21;
            const file = editor.serialize();
            a.material.roughness = .9;
            await editor.applySettings(file);
            const roundtrip = a.material.roughness === .21 && b.material === a.material;
            document.querySelector('[data-preset=water]').click();
            for (let i = 0; i < 100 && !a.material.riverFlow; i++) await new Promise((resolve) => setTimeout(resolve, 20));
            const waterFile = editor.serialize();
            await editor.applySettings(waterFile);
            const waterRoundtrip = a.material.userData.lpmview_water?.version === 2 && !!a.material.riverFlow && a.material === b.material;
            const nodesFile = waterFile.materials[0];
            nodesFile.water.version = 1; delete nodesFile.water.network;
            await editor.applySettings(waterFile);
            const legacyWaterRoundtrip = a.material.userData.lpmview_water?.version === 1 && !!a.material.riverFlow && !!a.material.normalMap;
            const network = { nodes: [{ id: 'a', position: [100000, 3, 200004] }, { id: 'b', position: [99997, 3, 200000] }, { id: 'c', position: [100003, 3, 200000] }, { id: 'd', position: [100000, 3, 199996] }], edges: [['a', 'b'], ['a', 'c'], ['b', 'd'], ['c', 'd']] };
            const validGraph = !!validateFlowNetwork(network) && !validateFlowNetwork({ ...network, edges: [['a', 'missing']] });
            const field = createFlowField(network, [99995, 199995, 10, 10], 32);
            const pixels = field.getContext('2d').getImageData(0, 0, 32, 32).data;
            const hasBranches = pixels[8 * 32 * 4] !== pixels[(8 * 32 + 31) * 4];
            let snapped = null;
            const flowEditor = createFlowNetworkEditor({ scene, world, camera, controls, canvas: renderer.domElement, requestRender() {}, onChange(n) { snapped = n; } });
            flowEditor.start({ material: a.material, uses: [{ object: a, index: 0 }] }, { nodes: [], edges: [] });
            const rect = renderer.domElement.getBoundingClientRect();
            renderer.domElement.dispatchEvent(new PointerEvent('pointerdown', { button: 0, clientX: rect.left + 128, clientY: rect.top + 128, pointerId: 1 }));
            const surfaceSnap = snapped?.nodes[0]?.position.every((v, i) => Math.abs(v - [100000, 3, 200000][i]) < .001);
            flowEditor.stop(); const controlsRestored = controls.enabled;
            const background = createBackgroundController({ THREE: T, scene, renderer, camera, isEnvironmentEnabled: () => true });
            const sphere = background.ensureBgMesh(); background.syncToCamera(); const backgroundInsideFar = sphere.scale.x * 100000 < camera.far;
            const context = { roomId: 'r', controller: { supabase: { from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ data: { revision: 3, document: file } }) }) }) }), rpc: async (name, args) => ({ data: args.p_expected_revision + 1 }) } } };
            let restored = 0; const persistence = createRoomMaterialSettings({ getContext: () => context, apply: async () => { restored++; } });
            await persistence.refresh(models); await persistence.refresh(models); await persistence.save(file);
            const roomLoadedOnce = restored === 1;
            let attempts = 0;
            const retry = createRoomMaterialSettings({ getContext: () => context, apply: async () => { if (++attempts === 1) throw Error('offline'); } });
            await retry.refresh(models); window.dispatchEvent(new Event('online'));
            for (let n = 0; attempts < 2 && n < 10; n++) await Promise.resolve();
            const onlineRetry = attempts === 2; retry.dispose();
            let lateApply = 0, finish;
            context.controller = { supabase: { from: () => ({ select: () => ({ eq: () => ({ maybeSingle: () => new Promise((resolve) => { finish = resolve; }) }) }) }) } };
            const stale = createRoomMaterialSettings({ getContext: () => context, apply: async () => { lateApply++; } });
            const pending = stale.refresh(models); context.roomId = 'other'; finish({ data: { document: file, revision: 1 } }); await pending;
            const rejectsStale = lateApply === 0;
            persistence.dispose(); stale.dispose(); flowEditor.dispose(); background.dispose(); editor.dispose(); renderer.dispose();
            return { cards, thumbnail, texturePreviewSmall, selectionKeepsThumbnail, thumbnailCache, onlyEditedThumbnailRendered, sharedEdit, parseRestored, editsRestored, roundtrip, waterRoundtrip, legacyWaterRoundtrip, validGraph, hasBranches, surfaceSnap, controlsRestored, backgroundInsideFar, roomLoadedOnce, onlineRetry, rejectsStale };
        });
        assert.equal(result.cards, 1, 'Shared material appears once');
        for (const [key, value] of Object.entries(result)) if (key !== 'cards') assert.equal(value, true, key);
        assert.deepEqual(errors, []);
        console.log('[smoke] material editor, original comparison, surface snap, branches and room persistence passed');
    } finally { await page.close(); }
}
